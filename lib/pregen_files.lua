-- ai/ai.lua: AI parity (PLAN step 4), as v1 did it. Generated with the names embedded, because the AI scripts may not
-- have `path` or the registry. Level projectiles become shootable like their base (ShootableProjectile), and level
-- anti-air weapons get their base's anti-air settings.
local weapon_names, projectile_names = {}, {}
local function AddProjectileNames(tree)
   for name, children in pairs(tree) do
      projectile_names[name] = true
      for _, prefix in ipairs(TransformedProjectilePrefixes) do
         projectile_names[prefix .. name] = true
         for _, prefix2 in ipairs(TransformedProjectilePrefixes) do projectile_names[prefix2 .. prefix .. name] = true end
      end
      AddProjectileNames(children)
   end
end
for _, weapon_upgrade in ipairs(WeaponUpgrades) do
   weapon_names[weapon_upgrade.weapon_savename] = true
   AddProjectileNames(weapon_upgrade.projectile or {})
end
local function SortedKeys(t)
   local keys = {}
   for k in pairs(t) do table.insert(keys, k) end
   table.sort(keys)
   return keys
end
local function NameList(t)
   local parts = {}
   for _, k in ipairs(SortedKeys(t)) do table.insert(parts, '["' .. k .. '"] = true') end
   return "{ " .. table.concat(parts, ", ") .. " }"
end

local ai_file = io.open("../ai/ai.lua", "w")
ai_file:write([[
-- GENERATED by lib/pregen_files.lua; don't edit. AI parity for level weapons (llm/PLAN.md, step 4), as v1 did it:
-- level projectiles are shootable like their base, and level anti-air weapons get their base's anti-air settings.
-- Nothing else: copying more AI tables (data recursively, target priority lists) made the game hang (2026-11-11).
local IUW_FirstLevel, IUW_LastLevel = ]] .. FirstLevel .. ", " .. LastLevel .. "\n" .. [[
local IUW_Weapons = ]] .. NameList(weapon_names) .. "\n" .. [[
local IUW_Projectiles = ]] .. NameList(projectile_names) .. "\n" .. [[

for name in pairs(IUW_Projectiles) do
   if ShootableProjectile[name] then
      for level = IUW_FirstLevel, IUW_LastLevel do ShootableProjectile[name .. "_" .. level] = ShootableProjectile[name] end
   end
end

for name in pairs(IUW_Weapons) do
   if data.AntiAirFireProbability[name] ~= nil then
      for level = IUW_FirstLevel, IUW_LastLevel do
         local level_name = name .. "_" .. level
         data.AntiAirErrorStdDev[level_name] = data.AntiAirErrorStdDev[name]
         data.AntiAirOpenDoor[level_name] = data.AntiAirOpenDoor[name]
         data.AntiAirFireProbability[level_name] = data.AntiAirFireProbability[name]
         AntiAirFireProbabilityHumanAssist[level_name] = AntiAirFireProbabilityHumanAssist[name]
      end
   end
end
]])
ai_file:close()
